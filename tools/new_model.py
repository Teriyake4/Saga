#!/usr/bin/env python3
"""Generate a fail-closed Saga model-family scaffold."""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile


def namespace_id(model_id: str) -> str:
    # Prefix prevents IDs normalizing to C++ keywords (for example, "class").
    return "model_" + model_id.replace("-", "_")


def validate(name: str, model_id: str, output: Path) -> tuple[str, str]:
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name) or name in {"I", "Impl"}:
        raise ValueError("name must be a PascalCase C++ identifier (for example, AcmeText)")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", model_id):
        raise ValueError("id must be lowercase kebab-case (for example, acme-text)")
    if output.exists() and not output.is_dir():
        raise ValueError("output must be an existing directory or a new directory path")
    target = output / model_id
    if target.exists() or target.is_symlink():
        raise ValueError(f"refusing to overwrite existing path: {target}")
    return name, model_id


def files(name: str, model_id: str) -> dict[str, str]:
    header = f'''#pragma once

#include "saga/runtime/model_contracts.h"

#include <memory>

namespace saga::models::{namespace_id(model_id)} {{

class {name}Definition final : public runtime::IModelDefinition {{
public:
    runtime::ModelInspection inspect(const runtime::ArtifactMetadata&) const override;
    std::vector<backend::ModelProgram> describe_programs(
        const runtime::ModelInspection&, const runtime::RuntimeOptions&) const override;
    memory::Profile describe_resources(
        const runtime::ModelInspection&, const runtime::RuntimeOptions&) const override;
    std::unique_ptr<runtime::IModelRuntime> create_runtime(
        const runtime::ModelDescription&, runtime::IExecutionSession&) const override;
}};

class {name}Runtime final : public runtime::IModelRuntime {{
public:
    runtime::SequenceHandle create_sequence(std::uint64_t context_tokens) override;
    runtime::PendingStep prefill(runtime::PrefillRequest, runtime::ResourceLease) override;
    runtime::PendingStep decode(runtime::DecodeRequest, runtime::ResourceLease) override;
    runtime::Completion release_sequence(runtime::SequenceHandle) override;
}};

void register_model(runtime::ModelRegistry& registry);

}} // namespace saga::models::{model_id.replace('-', '_')}
'''
    source = f'''#include "{model_id}.h"

#include <stdexcept>
#include <string>
#include <utility>

namespace saga::models::{namespace_id(model_id)} {{
namespace {{
[[noreturn]] void unfinished(const char* method) {{
    throw std::logic_error(std::string("{name} scaffold is not implemented: ") + method);
}}
}}

runtime::ModelInspection {name}Definition::inspect(const runtime::ArtifactMetadata&) const {{
    unfinished("inspect");
}}
std::vector<backend::ModelProgram> {name}Definition::describe_programs(
    const runtime::ModelInspection&, const runtime::RuntimeOptions&) const {{
    unfinished("describe_programs");
}}
memory::Profile {name}Definition::describe_resources(
    const runtime::ModelInspection&, const runtime::RuntimeOptions&) const {{
    unfinished("describe_resources");
}}
std::unique_ptr<runtime::IModelRuntime> {name}Definition::create_runtime(
    const runtime::ModelDescription&, runtime::IExecutionSession&) const {{
    unfinished("create_runtime");
}}
runtime::SequenceHandle {name}Runtime::create_sequence(std::uint64_t) {{ unfinished("create_sequence"); }}
runtime::PendingStep {name}Runtime::prefill(runtime::PrefillRequest, runtime::ResourceLease) {{ unfinished("prefill"); }}
runtime::PendingStep {name}Runtime::decode(runtime::DecodeRequest, runtime::ResourceLease) {{ unfinished("decode"); }}
runtime::Completion {name}Runtime::release_sequence(runtime::SequenceHandle) {{ unfinished("release_sequence"); }}

void register_model(runtime::ModelRegistry& registry) {{
    registry.add("{model_id}", std::make_shared<const {name}Definition>());
}}
}} // namespace saga::models::{namespace_id(model_id)}
'''
    return {
        f"{model_id}.h": header,
        f"{model_id}.cpp": source,
        "CMakeLists.txt": f'''# Local integration snippet; include from the owning build only after implementation.
add_library(saga_model_{namespace_id(model_id)} {model_id}.cpp)
target_include_directories(saga_model_{namespace_id(model_id)} PRIVATE ${{PROJECT_SOURCE_DIR}}/include)
target_link_libraries(saga_model_{namespace_id(model_id)} PRIVATE saga_runtime)
''',
        "README.md": f'''# {name} model-family scaffold

Generated by `tools/new_model.py`. This is deliberately **not ready to run**.
Every generated model behavior throws `std::logic_error` until it is implemented.

- Definition: `{model_id}.h` / `{model_id}.cpp`
- Runtime: `{name}Runtime` (currently fail-closed)
- Registration entrypoint: `register_model(runtime::ModelRegistry&)`
- Local build integration: `CMakeLists.txt` (snippet only; not wired into Saga)

Do not infer tensor geometry, payload sizes, allocation requirements, tokenizer
semantics, numerical behavior, or readiness from a model name or file extension.
See `docs/adding-models.md` for the implementation and validation requirements.
''',
    }


def publish(stage: Path, target: Path) -> None:
    """Publish without replacing a target created by another process."""
    target.mkdir()  # Exclusive directory claim; unlike rename, cannot replace an empty directory.
    published: list[Path] = []
    try:
        for source in sorted(stage.iterdir()):
            destination = target / source.name
            os.link(source, destination)  # Exclusive file creation, never clobbers a competitor.
            published.append(destination)
        shutil.rmtree(stage)
    except BaseException:
        for destination in reversed(published):
            destination.unlink(missing_ok=True)
        target.rmdir()
        raise


def generate(name: str, model_id: str, output: Path) -> Path:
    name, model_id = validate(name, model_id, output)
    output.mkdir(parents=True, exist_ok=True)
    target = output / model_id
    stage = Path(tempfile.mkdtemp(prefix=f".{model_id}.tmp-", dir=output))
    try:
        for relative, content in sorted(files(name, model_id).items()):
            with (stage / relative).open("w", encoding="utf-8", newline="\n") as stream:
                stream.write(content)
        publish(stage, target)
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", required=True, help="PascalCase C++ definition class name")
    parser.add_argument("--id", required=True, help="lowercase kebab-case registry ID and directory")
    parser.add_argument("--output", type=Path, required=True, help="parent directory for the new family")
    args = parser.parse_args(argv)
    try:
        print(generate(args.name, args.id, args.output))
    except (OSError, ValueError) as error:
        print(f"new_model: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
